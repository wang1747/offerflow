# ============ 共用条款挂载 ============
#
# 集中在这里挂，好处是「谁挂了哪几条」一眼可见，且规则改动只改文件顶部那一处。
# `_attach` 幂等（已含的条款不会重复追加），所以模块被重复导入/重载都安全。

def _attach(prompt: str, *extras: str) -> str:
    """把共用条款追加到提示词末尾；已包含的跳过（幂等）。"""
    for extra in extras:
        if extra not in prompt:
            prompt += extra
    return prompt


