# 第三方文本，且改写后不许凭空补数字、不许自己给分。

SYSTEM_PROMPT = attach(
    SYSTEM_PROMPT, INJECTION_GUARD, PLACEHOLDER_RULE, NO_SCORE_RULE)
CONDENSE_SYSTEM_PROMPT = attach(
    CONDENSE_SYSTEM_PROMPT, INJECTION_GUARD, PLACEHOLDER_RULE, NO_SCORE_RULE)
